def validate_bundle(directory: Path) -> dict[str, Any]:
    expected = {filename for row in FILES for filename in (row[0], row[2], row[3])}
    demand(directory.is_dir() and {path.name for path in directory.iterdir()} == expected
           and all((directory / name).is_file() for name in expected), "six_file_set_mismatch")
    objects = {name: load(directory / name) for name in expected}
    hashes = {name: sha((directory / name).read_bytes()) for name in sorted(expected)}
    seen: set[str] = set()
    for packet_file, packet_schema, trace_file, cost_file in FILES:
        packet, trace, cost = (objects[name] for name in (packet_file, trace_file, cost_file))
        for obj, path in ((packet, packet_schema), (trace, "traces/cognition-trace.schema.json"),
                          (cost, "traces/cost-event.schema.json")):
            demand(schema_valid(obj, path), "artifact_schema_invalid")
            no_actor_leak(obj)
        pid, cid, cost_id = packet["packet_id"], trace["cognition_id"], cost["cost_event_id"]
        demand(len({pid, cid, cost_id} & seen) == 0, "duplicate_graph_id")
        seen.update((pid, cid, cost_id))
        demand(trace["target_id"] == cost["target_id"] == packet["issuer_id"] == "A1"
                and packet["issuer_layer"] == "L1"
                and cost["cognition_id"] == cid
                and trace["tick"] == cost["tick"] == packet["issued_at_tick"]
               and trace["turn_ref"] == cost["turn_ref"] and trace["lane"] == cost["lane"]
               and cost["request_ref"]["ref_id"] == pid
               and trace["schema_valid"] is True and cost["schema_valid"] is True,
               "graph_identity_mismatch")
        ref(trace["raw_output_ref"], "raw_" + pid, "raw_output", packet_file)
        ref(trace["parsed_packet_ref"], pid, "packet", packet_file)
        ref(trace["cost_event_ref"], cost_id, "cost_event", cost_file)
        ref(cost["request_ref"], pid, "packet", packet_file)
        ref(cost["cognition_trace_ref"], cid, "cognition_trace", trace_file)
        context_ref = {"ref_id": "ctx_A1_aster_heat_t000", "ref_type": "context",
                       "artifact_uri": "fixtures://contexts/aster-a1-context.example.json"}
        prompt_ref = {"ref_id": "prompt-l1-pulse-template", "ref_type": "prompt",
                      "artifact_uri": "fixtures://prompts/l1_pulse_context_template.md"}
        demand(trace["context_ref"] == cost["context_ref"] == context_ref
                and packet["source_context_id"] == context_ref["ref_id"]
                and trace["prompt_ref"] == prompt_ref, "graph_context_mismatch")
        demand(trace["model_evidence"]["run_mode"] == cost["run_mode"] == "dev"
               and trace["model_evidence"]["provider"] == cost["provider"] == "deterministic_fixture"
               and trace["model_evidence"]["model_id"] == cost["model_id"] == "fixture/aster-a4-e"
               and trace["fallback_used"] is False and cost["fallback_used"] is False
               and trace["retry_count"] == cost["retry_count"] == cost["fallback_count"] == 0
               and cost["input_tokens"] == cost["output_tokens"] == 0
               and cost["estimated_cost_usd"] == 0 and cost["free_model_used"] is True
               and cost["cost_estimate_status"] == "free_or_mock_zero"
               and cost["budget_status"] == "not_applicable",
               "mock_provenance_mismatch")
    return {"files": hashes, "coverage": {"schemas": "schema_only", "trace_cost": "observability_only"}}


