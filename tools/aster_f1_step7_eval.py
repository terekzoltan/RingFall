class EvidenceError(Exception):
    """A failed prerequisite or a false-green attempt, with a stable diagnostic."""


def demand(condition: bool, code: str) -> None:
    if not condition:
        raise EvidenceError(code)


def sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def strict_object(raw: bytes) -> dict[str, Any]:
    def unique(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in pairs:
            demand(key not in result, "duplicate_json_key")
            result[key] = value
        return result

    try:
        value = json.loads(raw.decode("utf-8"), object_pairs_hook=unique,
                           parse_constant=lambda _: (_ for _ in ()).throw(EvidenceError("nonfinite_json")))
    except (UnicodeError, ValueError, RecursionError) as exc:
        raise EvidenceError("invalid_json") from exc
    demand(isinstance(value, dict), "not_json_object")
    def finite(item: Any) -> None:
        if isinstance(item, float):
            demand(math.isfinite(item), "nonfinite_json")
        elif isinstance(item, dict):
            for child in item.values():
                finite(child)
        elif isinstance(item, list):
            for child in item:
                finite(child)
    finite(value)
    return value


def load(path: Path) -> dict[str, Any]:
    return strict_object(path.read_bytes())


def schema_valid(value: dict[str, Any], name: str) -> bool:
    schema = load(CONTRACTS / name)
    return Draft202012Validator(schema).is_valid(value)


def no_actor_leak(value: Any) -> None:
    if isinstance(value, dict):
        for key, item in value.items():
            normalized = re.sub("[^a-z]", "", key.lower())
            demand(not any(term in normalized for term in ("thermaldebt", "hiddenmetric")), "hidden_key")
            demand(key not in MUTATION_KEYS, "proposal_claims_mutation")
            no_actor_leak(item)
    elif isinstance(value, list):
        for item in value:
            no_actor_leak(item)
    elif isinstance(value, str):
        normalized = re.sub("[^a-z]", "", value.lower())
        demand(not any(term in normalized for term in ("thermaldebt", "hiddenthermal", "privatemetric",
                                                      "hiddenmetric")),
               "actor_hidden_leak")
    # Finite domain numbers such as 0.41/0.46 are not globally hidden strings.


