def verify_effects(core: dict[str, Any], packet: dict[str, Any], expected: dict[str, Any]) -> None:
    decision, state, links = core["core"], core["state"], core["links"]
    demand(decision["status"] == expected["core_status"]
           and sorted(decision["issues"]) == sorted(expected["issues"])
           and decision["disposition"] == expected["disposition"], "core_expectation_mismatch")
    demand(core["schema_validation"] == core["formal_proof"] == "not_run"
           and core["mutation_authorized"] is False
           and core["inputs"]["packet_id_sha256"] == sha(packet["packet_id"].encode())
           and core["inputs"]["source_context_id_sha256"] == sha(packet["source_context_id"].encode())
           and core["binding"]["status"] == "matched_projection_and_pulse", "core_binding_overclaim")
    trace, result, diff = links["trace"], links["result"], links["diff"]
    demand(isinstance(trace, dict) and isinstance(result, dict), "core_links_missing")
    pid = packet["packet_id"]
    trace_id, result_id, diff_id = ("action-trace:" + pid, "execution-result:" + pid, "state-diff:" + pid)
    demand(trace["id_sha256"] == sha(trace_id.encode()) and result["id_sha256"] == sha(result_id.encode())
           and trace["source_packet_id_sha256"] == result["source_packet_id_sha256"] == sha(pid.encode())
           and trace["execution_status"] == result["execution_status"]
           == {"succeeded": "success"}.get(expected["disposition"], expected["disposition"])
           and set(trace["validation"]) == {"schema", "authority", "context", "visibility"}
           and all(value in ("pass", "fail") for value in trace["validation"].values())
           and (all(value == "pass" for value in trace["validation"].values())
                if decision["status"] == "allowed" else "fail" in trace["validation"].values()),
           "core_link_mismatch")
    if expected["disposition"] == "succeeded":
        demand(packet["packet_type"] == "WorkOrderRequest", "unapproved_effect")
        demand(state["changed"] is True and state["initial_sha256"] != state["final_sha256"]
               and isinstance(diff, dict) and diff["id_sha256"] == sha(diff_id.encode())
               and diff["source_trace_id_sha256"] == sha(trace_id.encode())
               and diff["tick"] == packet["issued_at_tick"]
               and diff["change_class"] == "crew_status_available_to_unavailable"
               and trace["state_diff_ref_sha256"] == result["true_effect_ref_sha256"] == sha(diff_id.encode()),
               "core_effect_mismatch")
    else:
        demand(state["changed"] is False and state["initial_sha256"] == state["final_sha256"]
               and diff is None and trace["state_diff_ref_sha256"] is None
               and result["true_effect_ref_sha256"] is None, "unapproved_effect")


def verify_solver(report: dict[str, Any], raw: list[Any], core: dict[str, Any],
                  core_raw: bytes, packet: dict[str, Any], paths: tuple[Path, Path, Path, Path],
                  expected: dict[str, Any], mapper: Any, runner: Any) -> None:
    inputs = {name: path.read_bytes() for name, path in zip(("state", "candidate", "pulse", "context"), paths, strict=True)}
    required = {"record_type", "version", "p1_aggregate", "p1_evidence_sha256", "p1_input_sha256",
                "core_status", "core_issues", "core_disposition", "model_sha256", "executed_image",
                "inspected_platform", "declared_release", "mutation_authorized", "verdict", "solver_runs"}
    demand(isinstance(report, dict) and required <= report.keys(), "solver_report_incomplete")
    demand(report["record_type"] == "AsterF1P2SolverReport" and report["version"] == "0.1"
           and report["p1_aggregate"] == P1_EXPECTED and report["p1_evidence_sha256"] == sha(core_raw)
           and report["p1_input_sha256"] == {key: sha(value) for key, value in inputs.items()}
           and report["core_status"] == core["core"]["status"]
           and sorted(report["core_issues"]) == sorted(core["core"]["issues"])
           and report["core_disposition"] == core["core"]["disposition"]
           and report["model_sha256"] == sha(runner.MODEL.read_bytes())
           and report["executed_image"] == runner.IMAGE and report["inspected_platform"] == runner.PLATFORM
           and report["declared_release"] == runner.RELEASE and report["mutation_authorized"] is False
           and report["verdict"] == expected["verdict"], "solver_binding_mismatch")
    demand(len(raw) == len(report["solver_runs"]), "solver_capture_missing")
    for captured, receipt in zip(raw, report["solver_runs"], strict=True):
        demand(receipt == captured.receipt() and runner.IMAGE in captured.command
               and "--pull=never" in captured.command and "--network" in captured.command
               and "none" in captured.command and "readonly" in " ".join(captured.command),
               "solver_capture_tampered")
    verdict = expected["verdict"]
    if verdict == "unsupported":
        demand(not raw and report["agreement"] == "not_compared"
               and report["diagnostics"] == ["facts_or_core_issue_unmodeled"]
               and core["completeness"] in ("complete", "unsupported"), "unsupported_false_green")
        return
    demand(core["completeness"] == "complete" and not core["unsupported_predicates"]
           and report["agreement"] == "agreed" and not report["diagnostics"] and raw,
           "formal_not_proved")
    demand(report.get("engine") == "28.0.1 linux/amd64", "solver_engine_unverified")
    # Reconstruct the closed, fixed-symbol instance from fresh Core bytes; do not
    # accept a report's instance hash or a supplier verdict as an oracle.
    instance = mapper.map_p1(mapper.parse_p1(core_raw, inputs), runner.MODEL.read_text(encoding="utf-8"))
    demand(report["instance_sha256"] == sha(instance.text.encode()), "instance_drift")
    if verdict == "valid":
        demand(len(raw) == 2 and raw[0].code == raw[1].code == 0
               and raw[0].stdout == b"Model is consistent\n" and not raw[0].stderr
               and runner.witness_is_closed(raw[1].stdout, instance)
               and not raw[1].stderr and core["core"]["status"] == "allowed"
               and not core["core"]["issues"] and report["matched_errors"] == [], "positive_not_proved")
    else:
        named = runner.check_errors(raw[0])
        demand(verdict == "invalid" and len(raw) == 1 and named is not None
               and sorted(report["matched_errors"]) == sorted(named)
               and sorted(runner.PREDICATE_ISSUES[name] for name in named) == sorted(expected["issues"])
               and report["agreement"] == "agreed", "invalid_not_proved")


def evaluate_case(case: dict[str, Any], bundle: Path, parent: Path, mapper: Any, runner: Any,
                  captures: dict[str, list[Any]] | None = None) -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix="ringfall-step7-case-", dir=parent) as temp:
        paths = prepare(case, bundle, Path(temp))
        data = {name: path.read_bytes() for name, path in zip(("state", "candidate", "pulse", "context"), paths, strict=True)}
        packet = strict_object(data["candidate"])
        evidence: dict[str, Any] = {"name": case["name"], "expected_stage": case["stage"],
                                     "expected_verdict": case["verdict"], "hard_pass": False,
                                     "input_sha256": {name: sha(raw) for name, raw in data.items()},
                                     "coverage": {"schema": "schema_only", "core": None,
                                                  "formal": None, "trace_cost": "observability_only"}}
        schema = FILES[0][1] if case["kind"] == "tool" else FILES[1][1]
        if case["stage"] == "schema":
            demand(not schema_valid(packet, schema), "negative_schema_control_did_not_fail")
            evidence["diagnostic"] = "schema_invalid"
            return evidence
        demand(schema_valid(packet, schema) and schema_valid(strict_object(data["pulse"]),
               "packets/avatar-pulse-packet.schema.json"), "case_schema_invalid")
        if case["stage"] == "visibility":
            try:
                no_actor_leak(packet)
            except EvidenceError as exc:
                demand(str(exc) == "actor_hidden_leak", "negative_visibility_wrong_failure")
                evidence["diagnostic"] = str(exc)
                return evidence
            raise EvidenceError("negative_visibility_control_did_not_fail")
        no_actor_leak(packet)
        if case["stage"] == "input":
            failed = core_call(paths, runner)
            demand(failed.code == 4 and failed.stderr.strip() ==
                   ("p1_error:" + case["error"]).encode() and not failed.stdout, "input_control_false_green")
            evidence["coverage"]["core"] = "guarded_by_core_validator"
            evidence["diagnostic"] = case["error"]
            return evidence
        demand(case["stage"] == "differential", "unknown_case_stage")
        report, raw = runner.run(*paths)
        fresh = core_call(paths, runner)
        demand(fresh.code == 0 and not fresh.stderr, "fresh_core_unavailable")
        record = mapper.parse_p1(fresh.stdout, data)
        verify_effects(record, packet, case)
        verify_solver(report, raw, record, fresh.stdout, packet, paths, case, mapper, runner)
        if raw:
            demand(captures is not None, "private_capture_required")
            captures[case["name"]] = raw  # Keep genuine P2 bytes after P2's temp dir exits.
        evidence["coverage"]["core"] = "guarded_by_core_validator"
        evidence.update(core_evidence_sha256=sha(fresh.stdout), solver_report_sha256=sha(json.dumps(
            report, sort_keys=True, separators=(",", ":")).encode()),
            solver_runs=report["solver_runs"], model_sha256=report["model_sha256"],
            instance_sha256=report["instance_sha256"], observed_verdict=report["verdict"],
            core_status=record["core"]["status"], core_issues=record["core"]["issues"],
            disposition=record["core"]["disposition"], state=record["state"], links=record["links"],
            agreement=report["agreement"], diagnostic=report["diagnostics"])
        evidence["coverage"]["formal"] = "proved_by_refinery" if raw else "unsupported"
        evidence["hard_pass"] = case["verdict"] == "valid" and bool(raw)
        return evidence


def file_receipt(directory: Path, name: str) -> dict[str, Any]:
    try:
        raw = (directory / name).read_bytes()
    except OSError as exc:
        raise EvidenceError("private_evidence_unreadable") from exc
    return {"file": name, "bytes": len(raw), "sha256": sha(raw)}


def verify_private_evidence(directory: Path) -> dict[str, Any]:
    demand(directory.resolve().parent == PRIVATE_ROOT.resolve()
           and directory.name.startswith("ringfall-step7-"), "private_evidence_location_invalid")
    try:
        manifest = load(directory / "manifest.json")
        report = load(directory / "report.json")
        actual = {path.name for path in directory.iterdir() if path.is_file()}
    except OSError as exc:
        raise EvidenceError("private_evidence_unreadable") from exc
    _, runner = supplier()
    expected_supplier = {"image": runner.IMAGE, "model_sha256": sha(runner.MODEL.read_bytes()),
                         "release": runner.RELEASE, "platform": runner.PLATFORM}
    demand(manifest.get("source") == report.get("source") == source_snapshot()
           and manifest.get("p1_aggregate") == P1_EXPECTED
           and manifest.get("p2_aggregate") == P2_EXPECTED
           and manifest.get("supplier") == expected_supplier
           and manifest.get("report") == file_receipt(directory, "report.json"),
           "private_report_or_source_mismatch")
    cases = report.get("cases")
    saved = manifest.get("cases")
    demand(isinstance(cases, list) and isinstance(saved, list) and len(cases) == len(saved),
           "private_case_mismatch")
    files = {"report.json", "manifest.json"}
    for case, entry in zip(cases, saved, strict=True):
        demand(isinstance(case, dict) and isinstance(entry, dict)
               and case.get("name") in REQUIRED_CASES
               and entry.get("name") == case.get("name")
               and entry.get("input_sha256") == case.get("input_sha256")
               and entry.get("core_evidence_sha256") == case.get("core_evidence_sha256")
               and entry.get("p2_report_sha256") == case.get("solver_report_sha256")
               and entry.get("model_sha256") == case.get("model_sha256")
               and entry.get("instance_sha256") == case.get("instance_sha256")
               and isinstance(entry.get("solver_runs"), list)
               and len(entry["solver_runs"]) == len(case.get("solver_runs", [])),
               "private_case_mismatch")
        mandatory = case.get("expected_stage") == "differential" and case.get("expected_verdict") in ("valid", "invalid")
        demand(not mandatory or bool(entry["solver_runs"]), "private_capture_missing")
        demand(not entry["solver_runs"] or case.get("model_sha256") == expected_supplier["model_sha256"],
               "private_supplier_mismatch")
        for index, (row, receipt) in enumerate(zip(entry["solver_runs"], case.get("solver_runs", []), strict=True)):
            demand(row.get("receipt") == receipt and expected_supplier["image"] in receipt["command"],
                   "private_receipt_mismatch")
            for stream in ("stdout", "stderr"):
                name = f"{case['name']}-{index}.{stream}"
                files.add(name)
                actual_receipt = file_receipt(directory, name)
                demand(row.get(stream) == actual_receipt
                       and actual_receipt["bytes"] == receipt[stream + "_bytes"]
                       and actual_receipt["sha256"] == receipt[stream + "_sha256"],
                       "private_capture_mismatch")
            demand(row["stdout"]["bytes"] + row["stderr"]["bytes"] <= 65_536,
                   "private_capture_truncated")
    demand(actual == files, "private_evidence_file_set_mismatch")
    return {"directory": str(directory), "source_aggregate": manifest["source"]["aggregate"],
            "report": manifest["report"], "manifest": file_receipt(directory, "manifest.json"),
            "capture_files": len(files) - 2}


def write_private_evidence(directory: Path, report: dict[str, Any],
                           captures: dict[str, list[Any]], runner: Any) -> dict[str, Any]:
    manifest: dict[str, Any] = {"source": report["source"], "p1_aggregate": P1_EXPECTED,
                                "p2_aggregate": P2_EXPECTED,
                                "supplier": {"image": runner.IMAGE, "model_sha256": sha(runner.MODEL.read_bytes()),
                                             "release": runner.RELEASE, "platform": runner.PLATFORM},
                                "cases": []}
    try:
        for case in report["cases"]:
            name = case["name"]
            raw = captures.get(name, [])
            demand([item.receipt() for item in raw] == case.get("solver_runs", []),
                   "private_receipt_mismatch")
            entry = {"name": name, "input_sha256": case["input_sha256"],
                     "core_evidence_sha256": case.get("core_evidence_sha256"),
                     "p2_report_sha256": case.get("solver_report_sha256"),
                     "model_sha256": case.get("model_sha256"),
                     "instance_sha256": case.get("instance_sha256"), "solver_runs": []}
            for index, item in enumerate(raw):
                receipt = item.receipt()
                demand(len(item.stdout) + len(item.stderr) <= 65_536, "private_capture_truncated")
                saved = {"receipt": receipt}
                for stream in ("stdout", "stderr"):
                    filename = f"{name}-{index}.{stream}"
                    (directory / filename).write_bytes(getattr(item, stream))
                    saved[stream] = file_receipt(directory, filename)
                    demand(saved[stream]["sha256"] == receipt[stream + "_sha256"]
                           and saved[stream]["bytes"] == receipt[stream + "_bytes"],
                           "private_capture_mismatch")
                entry["solver_runs"].append(saved)
            manifest["cases"].append(entry)
        (directory / "report.json").write_bytes((json.dumps(
            report, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode())
        manifest["report"] = file_receipt(directory, "report.json")
        (directory / "manifest.json").write_bytes((json.dumps(
            manifest, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode())
    except OSError as exc:
        raise EvidenceError("private_evidence_unreadable") from exc
    return verify_private_evidence(directory)


def evaluate(expected_aggregate: str) -> tuple[dict[str, Any], dict[str, Any]]:
    frozen = source_snapshot()
    demand(frozen["aggregate"] == expected_aggregate, "source_not_frozen_as_requested")
    mapper, runner = supplier()
    suite = load(CASES)
    rows = required_cases(suite)
    demand(PRIVATE_ROOT.is_dir(), "private_evidence_root_unavailable")
    private = Path(tempfile.mkdtemp(prefix="ringfall-step7-", dir=PRIVATE_ROOT))
    captures: dict[str, list[Any]] = {}
    with tempfile.TemporaryDirectory(prefix="ringfall-step7-") as temp:
        parent = Path(temp)
        bundle = parent / "a4h"
        graph = generate(bundle)
        cases = [evaluate_case(case, bundle, parent, mapper, runner, captures) for case in rows]
    demand({row["coverage"]["formal"] for row in cases} == {"proved_by_refinery", "unsupported", None}
           and {row["expected_stage"] for row in cases} == {"schema", "visibility", "input", "differential"}
           and sum(row["hard_pass"] for row in cases) == 2, "matrix_coverage_missing")
    supplier()  # Catch source drift between the preflight and completed suite.
    demand(source_snapshot() == frozen, "source_changed_after_freeze")
    report = {"suite_version": suite["suite_version"], "run_mode": "dev", "gate_claim": "local_scoped_evidence_only",
              "p1_aggregate": P1_EXPECTED, "p2_aggregate": P2_EXPECTED, "source": frozen,
              "coverage_classes": COVERAGE, "a4h": graph, "cases": cases,
              "candidate_hard_pass_count": 2, "no_full_world_or_wave_gate_claim": True,
              "private_evidence_dir": str(private)}
    receipt = write_private_evidence(private, report, captures, runner)
    demand(source_snapshot() == frozen, "source_changed_after_freeze")
    return report, receipt


def main() -> int:
    parser = argparse.ArgumentParser(description="Run local Aster Step 7 evidence, never authorize mutation")
    parser.add_argument("--expected-aggregate", help="four finalized Track E source files, hashed before this run")
    parser.add_argument("--verify-private", type=Path, help="read-only check of saved report, captures and candidate")
    args = parser.parse_args()
    try:
        if args.verify_private is not None:
            demand(args.expected_aggregate is None, "choose_one_evidence_mode")
            print(json.dumps(verify_private_evidence(args.verify_private), sort_keys=True))
            return 0
        demand(args.expected_aggregate is not None and re.fullmatch(r"[0-9a-f]{64}", args.expected_aggregate) is not None,
               "expected_aggregate_required")
        report, receipt = evaluate(args.expected_aggregate)
    except (EvidenceError, OSError, ValueError, KeyError, TypeError, subprocess.TimeoutExpired) as exc:
        print("step7_evidence_blocked:" + (str(exc) if isinstance(exc, EvidenceError) else "input_or_runtime_failure"), file=sys.stderr)
        return 1
    print(json.dumps(report, sort_keys=True, separators=(",", ":")))
    print("step7_private_receipts:" + json.dumps(receipt, sort_keys=True), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
